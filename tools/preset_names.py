def clean(lst):
    return [w for w in lst if not w.endswith("_X") and "PLACEHOLDER" not in w and w not in ("SEISMIC_X",)]

used = set()
def take(lst):
    for w in lst:
        if w not in used and w not in FORBIDDEN and not any(f in w for f in ("SAW","SINE","SQUARE","TRIANGLE","PULSE")):
            used.add(w); yield w

names = []
for cat, count in ORDER:
    nouns_src, mods_src = POOLS[cat]
    nouns = list(take(clean(nouns_src))) ; mods = list(take(clean(mods_src)))
    extraN = take(clean(EXTRA_N)); extraA = take(clean(EXTRA_A))
    while len(nouns) < count: nouns.append(next(extraN))
    pairs = min(count - round(count * 0.3), len(mods))
    for w in extraA:
        if pairs >= count - round(count * 0.3): break
        mods.append(w); pairs += 1
    singles = count - pairs
    print(cat, "nouns", len(nouns), "mods", len(mods), "singles", singles, "pairs", pairs)
    # return unused words so later categories can't see them as used? (they stay reserved: fine, keeps flavour)
    out = []
    for i in range(count):
        n = nouns[i]
        if i % 5 in (1, 3) or i >= singles + pairs:   # interleave singles and pairs
            pass
        out.append(n)
    # build: indices chosen deterministically so singles / pairs alternate through the category
    pair_idx = [i for i in range(count) if (i * 3) % 5 >= 2][:pairs]
    if len(pair_idx) < pairs: pair_idx += [i for i in range(count) if i not in pair_idx][:pairs - len(pair_idx)]
    pset = set(pair_idx)
    k = 0
    for i in range(count):
        if i in pset:
            sep = "//" if k % 7 == 3 else " "
            names.append((cat, mods[k] + sep + nouns[i])); k += 1
        else:
            names.append((cat, nouns[i]))

# ---- validation
errors = []
allwords = []
for cat, n in names:
    ws = re.split(r"[ /]+", n)
    allwords += ws
    if not (1 <= len(ws) <= 3): errors.append("word count: " + n)
    for w in ws:
        if w in FORBIDDEN or any(f in w for f in ("SAW","SINE","SQUARE","TRIANGLE","PULSE")): errors.append("forbidden: " + n)
c = collections.Counter(allwords)
dups = [w for w, k in c.items() if k > 1]
if dups: errors.append("repeated words: " + ",".join(dups))
if len(names) != 777: errors.append("count %d" % len(names))
if len(set(n for _, n in names)) != len(names): errors.append("duplicate names")
if errors:
    print("\n".join(errors[:40])); sys.exit(1)

old = [l.split("  ")[1].strip() for l in open(sys.argv[1]) if re.search(r"peak .* dBFS", l)]
oldcat = []
for l in open(sys.argv[1]):
    m = re.match(r"\s+(.*?)\s*(BASS|808|SUB|LEAD|SYNTH|PLUCK|PAD|PERCUSSION|FX)\s+peak", l)
    if m: oldcat.append((m.group(1), m.group(2)))
assert len(oldcat) == 777
for (o, oc), (c2, n) in zip(oldcat, names):
    assert oc == c2, (o, oc, c2)

with open(sys.argv[2], "w") as f:
    f.write("// Generated by the preset-naming script (0.8.1): factory preset names in bank order. Do not edit by hand.\n")
    for (o, oc), (c2, n) in zip(oldcat, names):
        f.write('"%s",   // %s | %s\n' % (n, oc, o))
with open(sys.argv[3], "w", newline="") as f:
    w = csv.writer(f); w.writerow(["index", "category", "name", "previous_name"])
    for i, ((o, oc), (c2, n)) in enumerate(zip(oldcat, names)): w.writerow([i + 1, oc, n, o])
print("OK", len(names), "names,", len(allwords), "unique words")
